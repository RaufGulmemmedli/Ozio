export interface MenuItem {
  id: number;
  /** `menu.<restaurantSlug>.<itemKey>` is NOT used: demo copy is inline, see the fixtures. */
  name: string;
  description: string;
  /** AZN. */
  price: number;
  /** Set when the item is discounted; always greater than `price`. */
  oldPrice: number | null;
  /** Grams or millilitres, already worded ("250 q", "0,5 l"). */
  portion: string | null;
  /** Badge on the card. */
  tag: 'popular' | 'new' | 'spicy' | 'vegetarian' | null;
}

export interface MenuSection {
  /** Keys `SECTION_ICON`; falls back to `default`. */
  id: string;
  title: string;
  items: MenuItem[];
}

export interface Restaurant {
  id: number;
  name: string;
  /** One line under the name on the card. */
  tagline: string;
  cuisines: Cuisine[];
  /** 0–5, one decimal. */
  rating: number;
  ratingCount: number;
  /** Minutes, the same pair `Store` carries. */
  deliveryTimeMin: number;
  deliveryTimeMax: number;
  /** AZN; `0` with `isDeliveryFree` for the free ones. */
  deliveryFee: number;
  isDeliveryFree: boolean;
  /** AZN — no equivalent on `Store`, but every delivery app has one. */
  minOrder: number;
  /** Cashback, like `Store.bonusPercentage`. */
  bonusPercentage: number;
  /** 1–3, drawn as ₼ / ₼₼ / ₼₼₼. */
  priceLevel: 1 | 2 | 3;
  /** Opening hours as Baku wall-clock "HH:mm". */
  opensAt: string;
  closesAt: string;
  menu: MenuSection[];
}

/** Cheapest item on the menu — the card's "from X ₼". */
export function cheapestItem(restaurant: Restaurant): number | null {
  const prices = restaurant.menu.flatMap((section) => section.items.map((item) => item.price));
  return prices.length > 0 ? Math.min(...prices) : null;
}

export function menuItemCount(restaurant: Restaurant): number {
  return restaurant.menu.reduce((sum, section) => sum + section.items.length, 0);
}

/**
 * Is it serving right now, in Baku?
 *
 * Mirrors `isOpenNow()` in the store module, including the over-midnight case (a kitchen that
 * closes at 03:00 is open at 01:00).
 */
export function isOpenNow(restaurant: Restaurant, now: Date = new Date()): boolean {
  const minutes = bakuMinutes(now);
  const open = toMinutes(restaurant.opensAt);
  const close = toMinutes(restaurant.closesAt);
  if (open === null || close === null) return true;
  return close > open ? minutes >= open && minutes < close : minutes >= open || minutes < close;
}

function toMinutes(value: string): number | null {
  const [h, m] = value.split(':').map(Number);
  if (h === undefined || m === undefined || Number.isNaN(h) || Number.isNaN(m)) return null;
  return h * 60 + m;
}

/** Baku wall-clock minutes since midnight, read through `Intl` so it does not depend on the host
 *  machine's time zone (the same approach `core/i18n/format.ts` uses for dates). */
function bakuMinutes(now: Date): number {
  const parts = new Intl.DateTimeFormat('en-GB', {
    timeZone: 'Asia/Baku',
    hour: '2-digit',
    minute: '2-digit',
    hourCycle: 'h23',
  }).formatToParts(now);
  const get = (type: 'hour' | 'minute') =>
    Number(parts.find((part) => part.type === type)?.value ?? '0');
  return get('hour') * 60 + get('minute');
}
